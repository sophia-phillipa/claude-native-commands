def load_register_tool() -> ModuleType:
    """Import the hyphenated script file under its module name (it is not importable by file name)."""
    cached = sys.modules.get(REGISTER_TOOL_MODULE)
    if cached is not None:
        return cached
    spec = importlib.util.spec_from_file_location(REGISTER_TOOL_MODULE, SCRIPT_PATH)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load {SCRIPT_PATH}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[REGISTER_TOOL_MODULE] = module
    spec.loader.exec_module(module)
    return module


