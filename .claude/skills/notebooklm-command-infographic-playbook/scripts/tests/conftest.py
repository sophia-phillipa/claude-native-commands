def standalone_wrapper(source: str) -> str:
    """Section 1 wrapper, written here independently of the script under test."""
    head = (
        '<!doctype html>\n<html lang="pt-BR" data-theme="dark">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
        "<style>body{margin:0}[hidden]{display:none!important}img{max-width:100%}</style>\n"
    )
    return head + source + "\n</html>\n"


def vector_html(strings: list[str], extra: str = "") -> str:
    """A passing vector: one paragraph per closed-list string, plus optional extra markup."""
    paragraphs = "".join(f"<p>{html.escape(text)}</p>" for text in strings)
    return (
        '<!doctype html>\n<html lang="pt-BR">\n<head><meta charset="utf-8"><title>t</title></head>\n'
        f"<body>\n{paragraphs}\n{extra}\n</body>\n</html>\n"
    )


def seed_strings() -> list[str]:
    """Closed-list strings of the seed blueprint, in contract order (section 3)."""
    bp = BLUEPRINT_SEED
    strings = [bp["command"], bp["category"], *bp["ui"].values(), bp["identity"]["purpose"]]
    strings += [step["label"] for step in bp["flow"]["steps"]]
    strings += [edge["verb"] for edge in bp["flow"]["edges"]]
    for flag in bp["connections"]["flags"]:
        strings += [flag["text"], flag["label"]]
    for related in bp["connections"]["related"]:
        strings += [related["command"], related["label"]]
    strings += bp["contrast"]["when"] + bp["contrast"]["pitfalls"] + [bp["contrast"]["example"]]
    return strings


class Project:
    """A fake project root. Never points at the real repository."""

    def __init__(self, root: Path, downloads: Path) -> None:
        self.root = root
        self.downloads = downloads

    @property
    def page_source(self) -> Path:
        return self.root / "src" / "comandos-nativos.html"

    @property
    def standalone(self) -> Path:
        return self.root / "comandos-nativos.html"

    @property
    def manifest(self) -> Path:
        return self.root / "assets" / "infographics" / "manifest.json"

    def slug_dir(self, slug: str = "compact") -> Path:
        return self.root / "assets" / "infographics" / slug

    def write_blueprint(self, blueprint: dict[str, Any] | None = None, slug: str = "compact") -> None:
        data = copy.deepcopy(BLUEPRINT_SEED if blueprint is None else blueprint)
        self.slug_dir(slug).mkdir(parents=True, exist_ok=True)
        (self.slug_dir(slug) / "blueprint.json").write_text(
            json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8"
        )

    def write_vector(self, text: str | None = None, slug: str = "compact") -> Path:
        target = self.slug_dir(slug) / "infographic.html"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text if text is not None else vector_html(seed_strings()), encoding="utf-8")
        return target

    def run(self, *args: str, cwd: Path | None = None) -> subprocess.CompletedProcess[str]:
        """Run the CLI with --root pointed at this fake project (no -I: Playwright lives in user site)."""
        return subprocess.run(
            [sys.executable, str(SCRIPT_PATH), "--root", str(self.root), *args],
            capture_output=True,
            text=True,
            encoding="utf-8",
            cwd=str(cwd or self.root),
            timeout=240,
            check=False,
        )


def result_json(completed: subprocess.CompletedProcess[str]) -> dict[str, Any]:
    """Parse the one JSON object a subcommand prints on stdout."""
    return json.loads(completed.stdout)


